#!/usr/bin/env python3
"""Build a Lockbox executable with an API key baked in."""
import argparse
import secrets
import subprocess
import sys


def main() -> None:
    parser = argparse.ArgumentParser(description="Build a Lockbox .exe with a baked-in API key.")
    parser.add_argument("entry", nargs="?", default="lockbox_gui.py",
                        help="entry script (default: lockbox_gui.py)")
    parser.add_argument("--name", default="lockbox", help="output name (default: lockbox)")
    parser.add_argument("--api-key", default=None,
                        help="API key to bake in (default: generate a new one)")
    parser.add_argument("--console", action="store_true",
                        help="keep a console window (use for lockbox.py)")
    args = parser.parse_args()

    key = args.api_key or secrets.token_hex(32)
    with open("_apikey.py", "w", encoding="utf-8") as f:
        f.write("# Generated by build_exe.py - do not commit.\n")
        f.write(f'BUILTIN_API_KEY = "{key}"\n')

    cmd = [sys.executable, "-m", "PyInstaller", "--onefile", "--clean", "--name", args.name]
    if sys.platform.startswith("win") and not args.console:
        cmd.append("--windowed")
    cmd.append(args.entry)
    subprocess.check_call(cmd)

    suffix = ".exe" if sys.platform.startswith("win") else ""
    print("\nBuilt dist/%s%s" % (args.name, suffix))
    if args.api_key:
        print("Baked in the API key you provided.")
    else:
        print("Generated a new API key - set this value as API_KEY on the KeyVault server:")
    print(key)


if __name__ == "__main__":
    main()
